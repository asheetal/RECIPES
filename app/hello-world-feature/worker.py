#!/usr/bin/env python3
"""Hello World worker: read xlsx, emit a one-page PDF via fpdf2."""
import sys, json
from fpdf import FPDF

def main():
    if len(sys.argv) < 3:
        print(json.dumps({"ok": False, "error": "usage: worker.py <xlsx> <out.pdf>"}))
        return 2
    xlsx_path, out_pdf = sys.argv[1], sys.argv[2]
    try:
        import openpyxl
        wb = openpyxl.load_workbook(xlsx_path, read_only=True, data_only=True)
        sheets = wb.sheetnames
        rows = 0; cols = 0
        for name in sheets:
            ws = wb[name]
            rows += ws.max_row or 0
            cols = max(cols, ws.max_column or 0)
        wb.close()
    except Exception as e:
        print(json.dumps({"ok": False, "error": f"cannot read workbook: {e}"}))
        return 3

    pdf = FPDF()
    pdf.add_page()
    pdf.set_font("Helvetica", "B", 18)
    pdf.cell(0, 12, "Hello World", ln=True)
    pdf.set_font("Helvetica", "", 11)
    pdf.ln(4)
    pdf.multi_cell(0, 6, "This PDF was generated by the RA.recipes Hello World recipe.")
    pdf.ln(6)
    pdf.set_font("Helvetica", "B", 12)
    pdf.cell(0, 8, "Workbook facts", ln=True)
    pdf.set_font("Helvetica", "", 11)
    for s in sheets:
        pdf.cell(0, 6, f"Sheet: {s}", ln=True)
    pdf.cell(0, 6, f"Total rows: {rows}", ln=True)
    pdf.cell(0, 6, f"Maximum columns: {cols}", ln=True)
    pdf.output(out_pdf)
    print(json.dumps({"ok": True, "facts": {"sheets": sheets, "rows_total": rows, "cols_max": cols}}))
    return 0

if __name__ == "__main__":
    sys.exit(main())
